/**
 * Procedural Web Audio API synth generator for instant ambient background music
 * Used as fallback or instant generator so BGM is 100% reliable offline.
 */
export function generateProceduralBgmBuffer(audioCtx, durationSec = 30, style = 'lofi-beats') {
  const sampleRate = audioCtx.sampleRate;
  const numSamples = Math.ceil(sampleRate * durationSec);
  const buffer = audioCtx.createBuffer(2, numSamples, sampleRate);
  const left = buffer.getChannelData(0);
  const right = buffer.getChannelData(1);

  // Frequencies for chord progression (Cmaj7 -> Am7 -> Fmaj7 -> G7)
  const chordFreqs = [
    [261.63, 329.63, 392.00, 493.88], // Cmaj7
    [220.00, 261.63, 329.63, 392.00], // Am7
    [174.61, 220.00, 261.63, 329.63], // Fmaj7
    [196.00, 246.94, 293.66, 349.23]  // G7
  ];

  const chordDuration = 4.0; // 4 seconds per chord

  for (let i = 0; i < numSamples; i++) {
    const t = i / sampleRate;
    const chordIdx = Math.floor(t / chordDuration) % chordFreqs.length;
    const currentChord = chordFreqs[chordIdx];

    let sampleL = 0;
    let sampleR = 0;

    // Warm ambient pad
    currentChord.forEach((freq, idx) => {
      const osc = Math.sin(2 * Math.PI * freq * t) * 0.15;
      const sub = Math.sin(2 * Math.PI * (freq / 2) * t) * 0.10;
      const pan = (idx / (currentChord.length - 1)) * 0.6 - 0.3; // Stereo spread

      sampleL += (osc + sub) * (0.5 - pan);
      sampleR += (osc + sub) * (0.5 + pan);
    });

    // Soft lo-fi vinyl warmth / rain envelope
    const env = 0.8 + 0.2 * Math.sin(2 * Math.PI * 0.25 * t);
    left[i] = sampleL * env * 0.25;
    right[i] = sampleR * env * 0.25;
  }

  return buffer;
}
